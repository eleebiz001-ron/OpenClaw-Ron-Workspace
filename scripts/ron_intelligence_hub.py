def safe_read(path):
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as f:
            return f.read()
    return None


def extract_hl_balance(snapshot_text):
    if not snapshot_text:
        return "N/A"
    # Unified Account logic: Available to Trade = Portfolio Value - Total Margin Used
    portfolio = re.search(r"Portfolio Value:\s*([\d,\.]+)", snapshot_text)
    available = re.search(r"Available to Trade:\s*([\d,\.]+)", snapshot_text)
    
    if available:
        return f"Available: {available.group(1)} USDC (Portfolio: {portfolio.group(1)} if portfolio else 'N/A')"
    
    return "Unified Account Syncing..."


def extract_paper_summary(text):
    if not text:
        return "No AI Research Summary found."
    # Grab first 12 non-empty lines to keep it concise
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    return "\n".join(lines[:12])


def generate_report():
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    snapshot_text = safe_read(SNAPSHOT_PATH)
    paper_text = safe_read(PAPER_SUMMARY_PATH)

    hl_balance = extract_hl_balance(snapshot_text)
    paper_summary = extract_paper_summary(paper_text)
    followers = get_real_follower_count()

    report = f"""# 🤵‍♂️ Ron’s Intelligence Hub
Updated: {timestamp}

## 🐦 X (Global) Growth (@EunLee_Global)
- Followers: **{followers}** (Target: 100)

## 📈 Hyperliquid Unified Account
- Status: {hl_balance}

## 🧠 AI Research (Hugging Face Daily)
{paper_summary}

---
*Auto-generated by ron_intelligence_hub.py*
"""

    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(report)

    return OUTPUT_PATH


if __name__ == "__main__":
    output = generate_report()
    print(f"Intelligence Hub written to: {output}")
