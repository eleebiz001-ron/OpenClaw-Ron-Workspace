#!/usr/bin/env python3
import os
import re
import subprocess
from datetime import datetime

# Inputs
SNAPSHOT_PATH = "/Users/ieunchul/Documents/Obsidian Vault/2nd_Brain/04_Finance/Daily_Trading_Snapshot.md"
PAPER_SUMMARY_PATH = "/Users/ieunchul/Documents/Obsidian Vault/2nd_Brain/03_Resources/AI_Research_Summaries/2026-02-18_HuggingFace_Summary.md"

# Output
OUTPUT_PATH = "/Users/ieunchul/Documents/Obsidian Vault/2nd_Brain/00_Inbox/🤵‍♂️_Intelligence_Hub.md"

